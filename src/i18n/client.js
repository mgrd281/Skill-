// "{n} من {total}" => القيم من vars
export const fmt = (s, vars = {}) => s.replace(/\{(\w+)\}/g, (_, k) => (k in vars ? String(vars[k]) : ""));
// رابط الصفحة الرئيسية بلغة الصفحة الحالية: العربية في الجذر وغيرها تحت /<اللغة>/
